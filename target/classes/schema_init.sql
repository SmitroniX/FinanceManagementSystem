-- ----------------------------------------------------------------------------
-- 1. USERS TABLE
-- Stores authenticated users and system administrators.
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME       VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(120) NOT NULL,
    PASSWORD_HASH   VARCHAR2(256) NOT NULL,
    ROLE            VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    PHONE_NUMBER    VARCHAR2(25),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'USER', 'AUDITOR')),
    CONSTRAINT CHK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'CLOSED'))
);

-- ----------------------------------------------------------------------------
-- 2. CATEGORIES TABLE
-- Stores income and expense classification categories.
-- ----------------------------------------------------------------------------
CREATE TABLE CATEGORIES (
    CATEGORY_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(10),
    NAME            VARCHAR2(60) NOT NULL,
    CATEGORY_TYPE   VARCHAR2(15) NOT NULL,
    COLOR_HEX       VARCHAR2(10) DEFAULT '#4A90E2',
    ICON_NAME       VARCHAR2(40) DEFAULT 'tag',
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CAT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_CAT_TYPE CHECK (CATEGORY_TYPE IN ('INCOME', 'EXPENSE')),
    CONSTRAINT UQ_CAT_NAME_USER UNIQUE (USER_ID, NAME, CATEGORY_TYPE)
);

-- ----------------------------------------------------------------------------
-- 3. ACCOUNTS TABLE
-- Implements OOP Polymorphic Account representation (Savings, Checking, Investment).
-- ----------------------------------------------------------------------------
CREATE TABLE ACCOUNTS (
    ACCOUNT_ID          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER(10) NOT NULL,
    ACCOUNT_NUMBER      VARCHAR2(34) NOT NULL,
    ACCOUNT_NAME        VARCHAR2(100) NOT NULL,
    ACCOUNT_TYPE        VARCHAR2(20) NOT NULL,
    BALANCE             NUMBER(14,2) DEFAULT 0.00 NOT NULL,
    CURRENCY            VARCHAR2(5) DEFAULT 'USD' NOT NULL,
    INTEREST_RATE       NUMBER(5,2) DEFAULT 0.00,
    OVERDRAFT_LIMIT     NUMBER(14,2) DEFAULT 0.00,
    MINIMUM_BALANCE     NUMBER(14,2) DEFAULT 0.00,
    PORTFOLIO_RISK      VARCHAR2(20) DEFAULT 'MODERATE',
    STATUS              VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ACC_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_ACC_NUMBER UNIQUE (ACCOUNT_NUMBER),
    CONSTRAINT CHK_ACC_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS', 'CHECKING', 'INVESTMENT')),
    CONSTRAINT CHK_ACC_STATUS CHECK (STATUS IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

-- ----------------------------------------------------------------------------
-- 4. TRANSACTIONS TABLE
-- Financial movement records linking source and destination accounts.
-- ----------------------------------------------------------------------------
CREATE TABLE TRANSACTIONS (
    TX_ID               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_REF              VARCHAR2(60) NOT NULL,
    SOURCE_ACCOUNT_ID   NUMBER(10),
    DEST_ACCOUNT_ID     NUMBER(10),
    CATEGORY_ID         NUMBER(10),
    AMOUNT              NUMBER(14,2) NOT NULL,
    TX_TYPE             VARCHAR2(15) NOT NULL,
    TX_DATE             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DESCRIPTION         VARCHAR2(255),
    STATUS              VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TX_SRC_ACC FOREIGN KEY (SOURCE_ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID) ON DELETE SET NULL,
    CONSTRAINT FK_TX_DST_ACC FOREIGN KEY (DEST_ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID) ON DELETE SET NULL,
    CONSTRAINT FK_TX_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE SET NULL,
    CONSTRAINT UQ_TX_REF UNIQUE (TX_REF),
    CONSTRAINT CHK_TX_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CHK_TX_TYPE CHECK (TX_TYPE IN ('INCOME', 'EXPENSE', 'TRANSFER')),
    CONSTRAINT CHK_TX_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED', 'REVERSED'))
);

-- ----------------------------------------------------------------------------
-- 5. BUDGETS TABLE
-- Budget limits per category and billing period for proactive financial control.
-- ----------------------------------------------------------------------------
CREATE TABLE BUDGETS (
    BUDGET_ID           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER(10) NOT NULL,
    CATEGORY_ID         NUMBER(10) NOT NULL,
    MONTH_YEAR          VARCHAR2(7) NOT NULL, -- Format: YYYY-MM (e.g., 2026-09)
    BUDGET_LIMIT        NUMBER(14,2) NOT NULL,
    ALERT_THRESHOLD     NUMBER(5,2) DEFAULT 80.00 NOT NULL, -- Alert when spent >= 80%
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BUDGET_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_BUDGET_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_BUDGET_LIMIT CHECK (BUDGET_LIMIT > 0),
    CONSTRAINT UQ_USER_CAT_MONTH UNIQUE (USER_ID, CATEGORY_ID, MONTH_YEAR)
);

-- ----------------------------------------------------------------------------
-- 6. AUDIT_LOGS TABLE
-- Complete audit trail for compliance, security, and DBMS viva demonstrations.
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    LOG_ID              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTION_TYPE         VARCHAR2(50) NOT NULL,
    TABLE_NAME          VARCHAR2(50) NOT NULL,
    RECORD_ID           NUMBER(10),
    USER_ID             NUMBER(10),
    DETAILS             VARCHAR2(500),
    LOG_TIMESTAMP       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ============================================================================
-- TRIGGERS FOR BUSINESS LOGIC AND INTEGRITY
-- ============================================================================

-- Trigger 1: Automatic Audit Logging for High-Value Transactions (> $5,000)
CREATE OR REPLACE TRIGGER TRG_AUDIT_HIGH_VALUE_TX
AFTER INSERT ON TRANSACTIONS
FOR EACH ROW
WHEN (NEW.AMOUNT >= 5000)
BEGIN
    INSERT INTO AUDIT_LOGS (
        ACTION_TYPE,
        TABLE_NAME,
        RECORD_ID,
        DETAILS,
        LOG_TIMESTAMP
    ) VALUES (
        'HIGH_VALUE_TRANSACTION',
        'TRANSACTIONS',
        :NEW.TX_ID,
        'Flagged transaction ref: ' || :NEW.TX_REF || ' with amount: $' || TO_CHAR(:NEW.AMOUNT, '999,999.99'),
        SYSTIMESTAMP
    );
END;
/

-- Trigger 2: Automatic Timestamp Maintenance on Accounts
CREATE OR REPLACE TRIGGER TRG_ACCOUNTS_TIMESTAMP
BEFORE UPDATE ON ACCOUNTS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

-- ============================================================================
-- PL/SQL STORED PROCEDURES (ACID TRANSACTION DEMONSTRATION)
-- ============================================================================

-- Stored Procedure: Execute Inter-Account Funds Transfer with Row-Level Locking
CREATE OR REPLACE PROCEDURE SP_TRANSFER_FUNDS (
    p_source_acc_id  IN  NUMBER,
    p_dest_acc_id    IN  NUMBER,
    p_amount         IN  NUMBER,
    p_description    IN  VARCHAR2,
    p_tx_ref         IN  VARCHAR2,
    p_status_out     OUT VARCHAR2,
    p_message_out    OUT VARCHAR2
) AS
    v_source_bal     NUMBER(14,2);
    v_source_overdraft NUMBER(14,2);
    v_source_status  VARCHAR2(20);
    v_dest_status    VARCHAR2(20);
BEGIN
    -- Input validation
    IF p_amount <= 0 THEN
        p_status_out := 'FAILED';
        p_message_out := 'Transfer amount must be strictly positive.';
        RETURN;
    END IF;

    IF p_source_acc_id = p_dest_acc_id THEN
        p_status_out := 'FAILED';
        p_message_out := 'Source and destination accounts cannot be identical.';
        RETURN;
    END IF;

    -- Lock and inspect source account
    SELECT BALANCE, OVERDRAFT_LIMIT, STATUS
      INTO v_source_bal, v_source_overdraft, v_source_status
      FROM ACCOUNTS
     WHERE ACCOUNT_ID = p_source_acc_id
       FOR UPDATE;

    IF v_source_status != 'ACTIVE' THEN
        p_status_out := 'FAILED';
        p_message_out := 'Source account is not active.';
        ROLLBACK;
        RETURN;
    END IF;

    -- Check available funds including allowed overdraft
    IF (v_source_bal + v_source_overdraft) < p_amount THEN
        p_status_out := 'FAILED';
        p_message_out := 'Insufficient funds in source account.';
        ROLLBACK;
        RETURN;
    END IF;

    -- Lock and verify destination account
    SELECT STATUS
      INTO v_dest_status
      FROM ACCOUNTS
     WHERE ACCOUNT_ID = p_dest_acc_id
       FOR UPDATE;

    IF v_dest_status != 'ACTIVE' THEN
        p_status_out := 'FAILED';
        p_message_out := 'Destination account is not active.';
        ROLLBACK;
        RETURN;
    END IF;

    -- Execute Atomic Balance Updates
    UPDATE ACCOUNTS
       SET BALANCE = BALANCE - p_amount
     WHERE ACCOUNT_ID = p_source_acc_id;

    UPDATE ACCOUNTS
       SET BALANCE = BALANCE + p_amount
     WHERE ACCOUNT_ID = p_dest_acc_id;

    -- Insert Transaction Record
    INSERT INTO TRANSACTIONS (
        TX_REF,
        SOURCE_ACCOUNT_ID,
        DEST_ACCOUNT_ID,
        AMOUNT,
        TX_TYPE,
        DESCRIPTION,
        STATUS
    ) VALUES (
        p_tx_ref,
        p_source_acc_id,
        p_dest_acc_id,
        p_amount,
        'TRANSFER',
        p_description,
        'COMPLETED'
    );

    COMMIT;
    p_status_out := 'SUCCESS';
    p_message_out := 'Transfer executed successfully.';

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        p_status_out := 'FAILED';
        p_message_out := 'One or both accounts do not exist.';
    WHEN OTHERS THEN
        ROLLBACK;
        p_status_out := 'ERROR';
        p_message_out := 'SQL Error: ' || SQLERRM;
END SP_TRANSFER_FUNDS;
/

