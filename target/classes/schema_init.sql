-- View 1: User Monthly Cash Flow Overview
CREATE OR REPLACE VIEW VW_USER_CASHFLOW AS
SELECT 
    a.USER_ID,
    TO_CHAR(t.TX_DATE, 'YYYY-MM') AS MONTH_YEAR,
    SUM(CASE WHEN t.TX_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) AS TOTAL_INCOME,
    SUM(CASE WHEN t.TX_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS TOTAL_EXPENSE,
    (SUM(CASE WHEN t.TX_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) - 
     SUM(CASE WHEN t.TX_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END)) AS NET_SAVINGS
FROM TRANSACTIONS t
JOIN ACCOUNTS a ON (t.SOURCE_ACCOUNT_ID = a.ACCOUNT_ID OR t.DEST_ACCOUNT_ID = a.ACCOUNT_ID)
WHERE t.STATUS = 'COMPLETED'
GROUP BY a.USER_ID, TO_CHAR(t.TX_DATE, 'YYYY-MM');

-- View 2: Budget Utilization with Status Warning
CREATE OR REPLACE VIEW VW_BUDGET_UTILIZATION AS
SELECT 
    b.BUDGET_ID,
    b.USER_ID,
    b.MONTH_YEAR,
    c.NAME AS CATEGORY_NAME,
    c.COLOR_HEX,
    b.BUDGET_LIMIT,
    NVL(SUM(t.AMOUNT), 0) AS ACTUAL_SPENT,
    (b.BUDGET_LIMIT - NVL(SUM(t.AMOUNT), 0)) AS REMAINING_AMOUNT,
    ROUND(NVL(SUM(t.AMOUNT), 0) / b.BUDGET_LIMIT * 100, 2) AS UTILIZATION_PCT,
    CASE 
        WHEN NVL(SUM(t.AMOUNT), 0) > b.BUDGET_LIMIT THEN 'EXCEEDED'
        WHEN NVL(SUM(t.AMOUNT), 0) >= (b.BUDGET_LIMIT * b.ALERT_THRESHOLD / 100) THEN 'WARNING'
        ELSE 'SAFE'
    END AS BUDGET_STATUS
FROM BUDGETS b
JOIN CATEGORIES c ON b.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN TRANSACTIONS t ON (
    t.CATEGORY_ID = b.CATEGORY_ID 
    AND t.TX_TYPE = 'EXPENSE' 
    AND t.STATUS = 'COMPLETED'
    AND TO_CHAR(t.TX_DATE, 'YYYY-MM') = b.MONTH_YEAR
)
GROUP BY b.BUDGET_ID, b.USER_ID, b.MONTH_YEAR, c.NAME, c.COLOR_HEX, b.BUDGET_LIMIT, b.ALERT_THRESHOLD;

COMMIT;
